CREATE DATABASE IF NOT EXISTS APP_DB;
CREATE SCHEMA IF NOT EXISTS APP_DB.REGISTRATION;

CREATE TABLE IF NOT EXISTS APP_DB.REGISTRATION.REGISTER (
    COMPANY_ID  NUMBER(38, 0) AUTOINCREMENT START 1 INCREMENT 1,
    COMPANY_NAME VARCHAR(100) NOT NULL,
    NAME        VARCHAR(100) NOT NULL,
    FIRST_NAME  VARCHAR(100) NOT NULL,
    EMAIL       VARCHAR(320) NOT NULL,
    TELEPHONE   VARCHAR(30) NOT NULL,
    OIDC_ISSUER VARCHAR(500),
    OIDC_SUBJECT VARCHAR(500),
    CONSTRAINT PK_REGISTER PRIMARY KEY (COMPANY_ID)
);

